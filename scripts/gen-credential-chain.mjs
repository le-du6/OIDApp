/** Generates one issuance/presentation chain, then synchronizes displayed scenario artifacts.
 * Dev only: ephemeral private keys are never written. RFC 9901; OID4VCI/VP 1.0.
 */
import { createHash, randomBytes } from 'node:crypto'
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { exportJWK, generateKeyPair, SignJWT } from 'jose'
const base = new URL('../', import.meta.url)
const IAT = 1767225600,
  NOW = IAT + 3600
const issuer = 'https://issuer.example',
  vct = 'https://credentials.example/identity_credential'
const nonce = 'cn-7f3b9d24aa',
  vpNonce = 'vpn-4Kd82mQxaz',
  audience = 'x509_san_dns:verifier.example'
const ik = await generateKeyPair('ES256'),
  wk = await generateKeyPair('ES256')
const issuerJwk = {
  ...(await exportJWK(ik.publicKey)),
  kid: 'vci-issuer-2026-01',
  alg: 'ES256',
  use: 'sig',
}
const walletJwk = await exportJWK(wk.publicKey)
const digest = (s) => createHash('sha256').update(s, 'ascii').digest('base64url')
const disclosures = [
  ['given_name', 'Camille'],
  ['family_name', 'Martin'],
  ['birthdate', '1990-01-01'],
].map(([name, value]) => {
  const salt = randomBytes(16).toString('base64url'),
    b64 = Buffer.from(JSON.stringify([salt, name, value])).toString('base64url')
  return { salt, name, value, b64, digest: digest(b64) }
})
const jwt = await new SignJWT({
  vct,
  _sd: disclosures.map((d) => d.digest),
  _sd_alg: 'sha-256',
  cnf: { jwk: walletJwk },
})
  .setProtectedHeader({ alg: 'ES256', typ: 'dc+sd-jwt', kid: issuerJwk.kid })
  .setIssuer(issuer)
  .setIssuedAt(IAT)
  .setExpirationTime(IAT + 365 * 86400)
  .sign(ik.privateKey)
const compact = [jwt, ...disclosures.map((d) => d.b64), ''].join('~')
const proof = await new SignJWT({ nonce })
  .setProtectedHeader({ alg: 'ES256', typ: 'openid4vci-proof+jwt', jwk: walletJwk })
  .setAudience(issuer)
  .setIssuedAt(IAT)
  .sign(wk.privateKey)
const selected = disclosures.map((d) => ({ ...d, revealed: d.name !== 'family_name' }))
const part = [jwt, ...selected.filter((d) => d.revealed).map((d) => d.b64), ''].join('~'),
  hash = digest(part)
const kb = await new SignJWT({ nonce: vpNonce, sd_hash: hash })
  .setProtectedHeader({ alg: 'ES256', typ: 'kb+jwt' })
  .setAudience(audience)
  .setIssuedAt(NOW)
  .sign(wk.privateKey)
function emit(path, values) {
  const source =
    '/** Generated by scripts/gen-credential-chain.mjs. Fictional data; fixed demonstration clock; public keys only. */\n' +
    Object.entries(values)
      .map(
        ([name, value]) =>
          `export const ${name} = ${JSON.stringify(value, null, 2)}${typeof value === 'object' ? ' as const' : ''}\n`,
      )
      .join('\n')
  writeFileSync(new URL(path, base), source)
}
emit('src/data/fixtures/oid4vci.ts', {
  VCI_ISSUER: issuer,
  VCI_VCT: vct,
  VCI_C_NONCE: nonce,
  VCI_ISSUED_AT: IAT,
  VCI_ISSUER_JWKS: { keys: [issuerJwk] },
  WALLET_PUBLIC_JWK: walletJwk,
  VCI_DISCLOSURES: disclosures,
  VCI_SD_JWT: jwt,
  VCI_SD_JWT_COMPACT: compact,
  VCI_JWT_PROOF: proof,
})
emit('src/data/fixtures/oid4vp.ts', {
  VP_VERIFIER_CLIENT_ID: audience,
  VP_NONCE: vpNonce,
  VP_DEMO_NOW: NOW,
  VP_ISSUER_JWKS: { keys: [issuerJwk] },
  VP_WALLET_JWK: walletJwk,
  VP_DISCLOSURES: selected,
  VP_SD_JWT: jwt,
  VP_PRESENTATION_PART: part,
  VP_SD_HASH: hash,
  VP_KB_JWT: kb,
  VP_PRESENTATION: part + kb,
})
const fmt = (o) => JSON.stringify(o, null, 2)
for (const module of ['oid4vci', 'oid4vp'])
  for (const file of readdirSync(new URL(`public/scenarios/${module}/`, base))) {
    if (!file.endsWith('.json')) continue
    const url = new URL(`public/scenarios/${module}/${file}`, base),
      scenario = JSON.parse(readFileSync(url, 'utf8'))
    for (const step of scenario.steps) {
      for (const token of step.tokens ?? []) {
        if (['sdjwt', 'sd-jwt-vc'].includes(token.id)) token.value = jwt
        if (token.id === 'proof') token.value = proof
        if (token.id === 'kb') token.value = kb
      }
      const exchange = step.request,
        request = exchange?.request,
        response = exchange?.response
      if (module === 'oid4vci' && request?.url === `${issuer}/credential`) {
        if (request.body) {
          const content = JSON.parse(request.body.content)
          if (content.proofs?.jwt) content.proofs.jwt = [proof]
          request.body = { ...request.body, content: fmt(content), representation: 'wire' }
        }
        if (response?.body)
          response.body = {
            type: 'json',
            content: fmt({ credentials: [{ credential: compact }] }),
            representation: 'wire',
          }
      }
      if (module === 'oid4vp' && step.id === 'direct-post') {
        const values = {
          vp_token: JSON.stringify({ identite: [part + kb] }),
          state: 'vp-state-8djeu2',
        }
        request.body = {
          type: 'form',
          content: new URLSearchParams(values).toString(),
          params: Object.entries(values).map(([name, value]) => ({ name, value })),
          representation: 'wire',
        }
      }
      if (module === 'oid4vp' && ['replay', 'attempt-replay'].includes(step.id)) {
        const values = {
          vp_token: JSON.stringify({ identite: [step.id === 'replay' ? part : part + kb] }),
        }
        request.body = {
          type: 'form',
          content: new URLSearchParams(values).toString(),
          representation: 'wire',
        }
      }
    }
    writeFileSync(url, fmt(scenario) + '\n')
  }
console.log(
  'One credential and holder key shared by VCI and VP; scenario artifacts synchronized. Private keys discarded.',
)
